// =============================================================================
//  Space Data Link Security (CCSDS 355.0-B-2), AUTHENTICATION-ONLY service on
//  the TC uplink. Protected TC frame layout:
//
//    | TC primary hdr 5 | SPI 2 | Sequence Number 4 | data field N | MAC 16 | FECF 2 |
//                       \____ Security Header ____/              \_ Security Trailer
//
//    MAC = first 16 octets of HMAC-SHA-256(key, primary hdr || security hdr || data)
//    Anti-replay: SN must be strictly greater than the last accepted SN.
//
//  Processing order on the spacecraft (as in the standard): CLTU decode ->
//  TC frame + FECF check -> SDLS ProcessSecurity -> FARM-1. A frame that fails
//  authentication never touches FARM state, so a spoofer cannot even cause a
//  lockout. Content stays in clear text (no encryption), which matters for
//  amateur-radio operation (see docs/09_Regulatory_and_Safety.md).
//
//  The 256-bit key lives in src/sdls_key.h, generated by tools/gen_sdls_key.py
//  (never committed). Without that file the build runs UNAUTHENTICATED and
//  says so in telemetry.
// =============================================================================
#pragma once
#include "tc.h"

namespace ccsds {

static const size_t kSdlsHdrLen = 6;     // SPI (2) + SN (4)
static const size_t kSdlsMacLen = 16;    // truncated HMAC-SHA-256

class Sdls {
 public:
  enum Result : uint8_t { SDLS_OK = 0, SDLS_DISABLED, SDLS_BAD_LENGTH, SDLS_BAD_SPI,
                          SDLS_REPLAY, SDLS_BAD_MAC };

  void init(const uint8_t* key, size_t key_len, uint16_t spi);
  bool enabled() const { return key_len_ != 0; }
  // `frame` is the whole TC frame; on SDLS_OK `f.data/f.data_len` are narrowed
  // to the protected data field.
  Result process(const uint8_t* frame, TcFrame& f);
  uint32_t last_sn() const { return last_sn_; }
  void set_last_sn(uint32_t sn) { if (sn > last_sn_) last_sn_ = sn; }   // restored by EGSE
  uint32_t auth_failures() const { return fails_; }

 private:
  uint8_t key_[32] = {0};
  size_t key_len_ = 0;
  uint16_t spi_ = 1;
  uint32_t last_sn_ = 0;
  uint32_t fails_ = 0;
};

}  // namespace ccsds
