inline uint16_t sat16(uint32_t v) { return v > 65535u ? (uint16_t)65535u : (uint16_t)v; }
inline uint32_t umin32(uint32_t a, uint32_t b) { return a < b ? a : b; }
inline void inc16(uint16_t& c) { if (c < 65535u) ++c; }

// u32 -> int32 two's complement without implementation-defined conversion (the EGSE
// stores the value as received and never interprets it, PB-4.1 sdls_sn).
inline int32_t as_i32(uint32_t v) {
  return v <= 0x7FFFFFFFu ? (int32_t)v : (int32_t)(v - 0x80000000u) - (int32_t)0x7FFFFFFF - 1;
}

inline int16_t clamp_i16(float v) {
  if (isnan(v)) return kNaI16;
  if (v > 32766.0f) return 32766;
  if (v < -32767.0f) return -32767;
  return (int16_t)lroundf(v);
}
inline int32_t clamp_i32(float v) {
  if (isnan(v)) return kNaI32;
  if (v > 2.0e9f) return 2000000000;
  if (v < -2.0e9f) return -2000000000;
  return (int32_t)lroundf(v);
}
inline uint16_t clamp_u16(float v) {        // 0..65534 (0xFFFF is the sentinel)
  if (isnan(v)) return kNaU16;
  if (v <= 0.0f) return 0;
  if (v >= 65534.0f) return 65534;
  return (uint16_t)lroundf(v);
}

// Upper-case hex of n octets. reserve() first: one transient allocation (PB-0.4).
String to_hex(const uint8_t* d, size_t n) {
  static const char kHex[] = "0123456789ABCDEF";
  String s;
  (void)s.reserve(2 * n);
  for (size_t i = 0; i < n; ++i) {
    s += kHex[d[i] >> 4];
    s += kHex[d[i] & 15];
  }
  return s;
}

// A notification String from n characters of a C string, reserved first.
String text_string(const char* t, size_t n) {
  String s;
  (void)s.reserve(n);
  s += t;
  return s;
}

int hexval(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c >= 'a' && c <= 'f') return c - 'a' + 10;
  if (c >= 'A' && c <= 'F') return c - 'A' + 10;
  return -1;
}

// Decodes an RPC hex argument: even length within [min_chars, max_chars] and fitting
// `cap` octets, hex digits only. Returns the octet count, 0 for anything else.
size_t hex_decode(const String& hex, uint8_t* out, size_t cap, size_t min_chars, size_t max_chars) {
  const size_t len = hex.length();
  if (len < min_chars || len > max_chars || (len & 1u) != 0 || len / 2 > cap) return 0;
  const char* p = hex.c_str();
  if (p == nullptr) return 0;
  for (size_t i = 0; i < len / 2; ++i) {
    const int hi = hexval(p[2 * i]), lo = hexval(p[2 * i + 1]);
    if (hi < 0 || lo < 0) return 0;
    out[i] = (uint8_t)((hi << 4) | lo);
  }
  return len / 2;
}

