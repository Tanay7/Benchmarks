void Flight::gen_timecorr() {
  if (!tc_ref_valid_) {                             // no reference frame yet: use the next one
    timecorr_request_ = true;
    return;
  }
  TimeCorrPacket p{};
  p.ref_mcfc = tc_ref_count_;
  p.sclk_coarse = (uint32_t)(tc_ref_sclk_us_ / 1000000u);
  p.sclk_fine = (uint16_t)(((tc_ref_sclk_us_ % 1000000u) << 16) / 1000000u);
  p.air_rate_code = tc_ref_rate_;
  p.ref_airtime_ms = sat16(tc_ref_airtime_ms_);
  uint8_t b[kTimeCorrLen];
  (void)emit(APID_TIMECORR, b, pack_timecorr(p, b), VC_RT_ENG);
}

void Flight::gen_mag() {
  MagPacket p{};
  uint8_t n = mstat_ob_.count();
  if (mstat_ib_.count() > n) n = mstat_ib_.count();
  if (mstat_body_.count() > n) n = mstat_body_.count();
  p.nsamples = n;
  p.flags = (uint8_t)(bit_if(mag_tx_keyed_, MAG_F_PA_KEYED) | bit_if(mstat_ob_.count() != 0, MAG_F_OB) |
                      bit_if(mstat_ib_.count() != 0, MAG_F_IB) | bit_if(mstat_body_.count() != 0, MAG_F_BMM150) |
                      bit_if(mag_lamp_, MAG_F_LAMP) | bit_if(magcal_.state() != 0, MAG_F_CAL));
  p.outboard = mag_vec(mstat_ob_, mag_ob_.ok());
  p.inboard = mag_vec(mstat_ib_, mag_ib_.ok());
  p.body = mag_vec(mstat_body_, true);
  p.rm3100_cycle_count = mag_ob_.ok() ? mag_ob_.cycle_count() : mag_ib_.cycle_count();
  mstat_ob_.reset();
  mstat_ib_.reset();
  mstat_body_.reset();
  mag_tx_keyed_ = false;
  mag_lamp_ = false;
  uint8_t b[kMagLen];
  (void)emit(APID_MAG, b, pack_mag(p, b), VC_RT_SCI);
}

// Independent attitude: TRIAD from gravity (accelerometer, primary) and the field, valid
// only while the accelerometer sees ~1 g. Field source (F-23): the calibrated boom RM3100
// (outboard, then inboard; MagCalStore applies B = M (B_raw - b), identity when cleared),
// rotated into body axes, else the BMM150.
bool Flight::triad(Quat& q, bool& from_rm3100) {
  from_rm3100 = false;
  if (!aru_valid_ || !(aru_last_.motion_flags & 2u)) return false;
  const AruReading& r = aru_last_;
  const Vec3 a{r.acc_mg[0] * 0.001f, r.acc_mg[1] * 0.001f, r.acc_mg[2] * 0.001f};
  const float an = v_norm(a);
  if (!(an > 0.9f && an < 1.1f)) return false;
  Vec3 m{0.0f, 0.0f, 0.0f};
  bool have = false;
  for (uint8_t u = 0; u < kMagUnits && !have; ++u) {
    float cal[3];
    if (!rm_fresh_[u] || !magcal_.apply(u, rm_ut_[u], cal)) continue;
    m.x = kRm3100ToBody[0][0] * cal[0] + kRm3100ToBody[0][1] * cal[1] + kRm3100ToBody[0][2] * cal[2];
    m.y = kRm3100ToBody[1][0] * cal[0] + kRm3100ToBody[1][1] * cal[1] + kRm3100ToBody[1][2] * cal[2];
    m.z = kRm3100ToBody[2][0] * cal[0] + kRm3100ToBody[2][1] * cal[1] + kRm3100ToBody[2][2] * cal[2];
    have = from_rm3100 = true;
  }
  if (!have && (r.motion_flags & 8u)) {
    m = Vec3{last_mag_ut_[0], last_mag_ut_[1], last_mag_ut_[2]};
    have = true;
  }
  if (!have) return false;
  return triad_ned(a, m, kGeomagInclDeg, kGeomagDeclDeg, q);
}

void Flight::gen_att() {
  AttPacket p{};
  for (uint8_t i = 0; i < 3; ++i) p.acc_mg[i] = p.gyro_ddps[i] = p.mag_dT[i] = kNaI16;
  for (uint8_t i = 0; i < 4; ++i) p.q_fus[i] = p.q_triad[i] = kNaI16;
  p.q_fus_acc_mrad = kNaU16;
  if (aru_valid_) {
    const AruReading& r = aru_last_;
    if (r.motion_flags & 1u) {
      p.flags |= ATT_F_QUAT;
      p.q_fus[0] = clamp_i16(r.qw * 16384.0f);
      p.q_fus[1] = clamp_i16(r.qx * 16384.0f);
      p.q_fus[2] = clamp_i16(r.qy * 16384.0f);
      p.q_fus[3] = clamp_i16(r.qz * 16384.0f);
      p.q_fus_acc_mrad = r.quat_acc_mrad;
    }
    if (r.motion_flags & 2u) {
      p.flags |= ATT_F_ACC;
      for (uint8_t i = 0; i < 3; ++i) p.acc_mg[i] = r.acc_mg[i];
    }
    if (r.motion_flags & 4u) {
      p.flags |= ATT_F_GYRO;
      for (uint8_t i = 0; i < 3; ++i) p.gyro_ddps[i] = r.gyro_ddps[i];
    }
    if (r.motion_flags & 8u) {
      p.flags |= ATT_F_MAG;
      for (uint8_t i = 0; i < 3; ++i) p.mag_dT[i] = clamp_i16(last_mag_ut_[i] * 10.0f);
    }
    if (r.motion_flags & 0x10u) p.flags |= ATT_F_MAG_SCALE;   // ARU page 0 flag b4 (C-21)
  }
  Quat q{1.0f, 0.0f, 0.0f, 0.0f};
  bool from_rm = false;
  if (triad(q, from_rm)) {
    p.flags |= ATT_F_TRIAD;
    if (from_rm) p.flags |= ATT_F_TRIAD_RM3100;
    p.q_triad[0] = clamp_i16(q.w * 16384.0f);
    p.q_triad[1] = clamp_i16(q.x * 16384.0f);
    p.q_triad[2] = clamp_i16(q.y * 16384.0f);
    p.q_triad[3] = clamp_i16(q.z * 16384.0f);
  }
  uint8_t b[kAttLen];
  (void)emit(APID_ATT, b, pack_att(p, b), VC_RT_SCI);
}

// ENV (PB-1.11): the ARU environment page as sent by the Nicla Sense ME. ARU flags b0 p,
// b1 BSEC, b2 T, b3 RH, b4 gas -> ENV b0 = b0, b1 = b1, b2 = (b2 | b3) with the missing
// one sent as its sentinel, b3 = b4.
void Flight::gen_env() {
  EnvPacket p{};
  p.p_cPa = kNaU32;
  p.t_cC = kNaI16;
  p.rh_cpct = kNaU16;
  p.iaq = p.iaq_s = kNaU16;
  p.co2eq_ppm = kNaU32;
  p.bvoc_cppm = kNaU16;
  p.gas_ohm = kNaU32;
  if (aru_env_valid_) {
    const AruReading& r = aru_last_;
    const uint8_t ef = r.env_flags;
    if (ef & 0x01u) {
      p.flags |= ENV_F_PRESSURE;
      p.p_cPa = r.p_pa;                             // Pa = 0.01 hPa, unchanged from the page
    }
    if (ef & 0x02u) {
      p.flags |= ENV_F_BSEC;
      p.iaq = r.iaq;
      p.iaq_s = r.iaq_s;
      p.co2eq_ppm = r.co2eq;
      p.bvoc_cppm = clamp_u16(r.bvoc_ppm * 100.0f);
      p.accuracy = r.bsec_accuracy <= 3u ? r.bsec_accuracy : (uint8_t)3u;   // BSEC 0..3
    }
    if (ef & 0x0Cu) {
      p.flags |= ENV_F_TH;
      if (ef & 0x04u) p.t_cC = clamp_i16(r.t_c * 100.0f);
      if (ef & 0x08u) p.rh_cpct = clamp_u16(r.rh * 100.0f);
    }
    if (ef & 0x10u) {
      p.flags |= ENV_F_GAS;
      p.gas_ohm = r.gas_ohm;
    }
  }
  uint8_t b[kEnvLen];
  (void)emit(APID_ENV, b, pack_env(p, b), VC_RT_SCI);
}

// =============================================================================
// Fault protection (1 Hz, PB-8.6 item 7)
// =============================================================================
void Flight::fdir_1hz(uint32_t now) {
  // --- command-loss timer (standard deep-space fault protection) ---
  if (cmd_loss_s_ && now - last_valid_tc_ms_ > cmd_loss_s_ * 1000u) {
    last_valid_tc_ms_ = now;                        // re-arm: one response per period
    fdir_flags_ |= FDIR_CMD_LOSS;
    if (fdir_mask_ & FDIR_CMD_LOSS) {
      evr(3, 0x0601, "COMMAND LOSS: no valid uplink for %lu s -> SAFE, default radio",
          (unsigned long)cmd_loss_s_);
      if (rcfg_.rate_code != kRadioRateCode || rcfg_.channel != kRadioChannel) {
        rcfg_.rate_code = kRadioRateCode;           // fall back to the mission-default link
        rcfg_.channel = kRadioChannel;
        pending_cfg_valid_ = false;
        revert_armed_ = false;
        radio_reconfig_pending_ = true;
      }
      if (hibernating_) exit_hibernate("command loss");
      enter_fdir_safe("command loss");
    }
  }
  // --- radio-change revert ---
  if (revert_armed_ && (int32_t)(now - revert_deadline_ms_) > 0) {
    revert_armed_ = false;
    pending_cfg_valid_ = false;
    rcfg_.rate_code = revert_cfg_.rate_code;
    rcfg_.channel = revert_cfg_.channel;
    radio_reconfig_pending_ = true;
    fdir_flags_ |= FDIR_RATE_REVERT;
    evr(3, 0x0602, "radio change NOT confirmed by uplink - reverting to ch %u code %u",
        (unsigned)revert_cfg_.channel, (unsigned)revert_cfg_.rate_code);
  }
  // --- TX inhibit timer ---
  if (tx_inhibit_ && (int32_t)(now - tx_inhibit_until_ms_) > 0) {
    tx_inhibit_ = false;
    fdir_flags_ &= (uint16_t)~FDIR_TX_INHIBIT;
    evr(1, 0x0603, "transmitter re-enabled");
  }
  // --- spacecraft bus temperature (Nicla Sense ME) ---
  if (!isnan(bus_temp_c_)) {
    if (bus_temp_c_ >= kBusTempRedC) fdir_flags_ |= FDIR_AVI_OVERTEMP;
    else if (bus_temp_c_ < kBusTempRedC - 5.0f) fdir_flags_ &= (uint16_t)~FDIR_AVI_OVERTEMP;
  }
  // --- I2C bus: bus clear + re-initialisation, at most once per 10 s ---
  if (bus_.consecutive_errors() > kI2cFdirErrors && (fdir_mask_ & FDIR_I2C_BUS) &&
      (!recovered_once_ || now - last_recover_ms_ >= kBusRecoverMinMs)) {
    fdir_flags_ |= FDIR_I2C_BUS;
    evr(3, 0x0605, "I2C bus fault (%u consecutive errors) - bus clear + re-init",
        (unsigned)bus_.consecutive_errors());
    bus_recover(now, "FDIR");
  }
  // F-25: FDIR I2C_BUS clears after kI2cBusHealthyS seconds without a new bus error.
  const uint32_t errs = bus_.errors();
  if (errs != i2c_err_snapshot_) {
    i2c_err_snapshot_ = errs;
    i2c_quiet_s_ = 0;
  } else if (i2c_quiet_s_ < 0xFFFFu) {
    ++i2c_quiet_s_;
  }
  if ((fdir_flags_ & FDIR_I2C_BUS) && i2c_quiet_s_ >= kI2cBusHealthyS) {
    fdir_flags_ &= (uint16_t)~FDIR_I2C_BUS;
    evr(1, 0x0609, "I2C bus healthy again: FDIR I2C_BUS cleared");
  }
  // --- instrument loss: the Nicla Sense ME (read every second) is the bus canary ---
  if (aru_fail_count_ > 5 && (sensor_health_ & SNS_NICLA_ME)) {
    sensor_health_ &= (uint16_t)~(SNS_NICLA_ME | kMeBits);
    fdir_flags_ |= FDIR_SENSOR_LOST;
    evr(3, 0x0606, "Nicla Sense ME stopped responding");
  } else if (aru_fail_count_ == 0 && (fdir_flags_ & FDIR_SENSOR_LOST) && (sensor_health_ & SNS_NICLA_ME)) {
    fdir_flags_ &= (uint16_t)~FDIR_SENSOR_LOST;
    evr(1, 0x0607, "Nicla Sense ME responding again");
  }
  // --- downlink congestion: routine packets fill a VC to 768 octets at most (PB-1.2) ---
  const size_t v0 = dl_.backlog(VC_RT_ENG), v1 = dl_.backlog(VC_RT_SCI);
  if (v0 > kVcCongestSetOctets || v1 > kVcCongestSetOctets) fdir_flags_ |= FDIR_VC_CONGEST;
  else if (v0 < kVcCongestClearOctets && v1 < kVcCongestClearOctets) fdir_flags_ &= (uint16_t)~FDIR_VC_CONGEST;
  // --- E22-400T37S abnormal-status reports stop 500 ms after the condition clears ---
  if (radio_fault_code_ >= kRadioFaultUnderVoltage && radio_fault_code_ <= kRadioFaultOvAndOt &&
      now - radio_fault_ms_ > kT37sFaultClearMs) {
    evr(1, 0x0315, "E22 abnormal status cleared (%u reports)", (unsigned)radio_fault_reports_);
    radio_fault_code_ = 0;
    fdir_flags_ &= (uint16_t)~(FDIR_RADIO_FAULT | FDIR_LOW_BUS_V | FDIR_PA_OVERTEMP);
  }
  // --- COP-1 ---
  if (farm_.state() == Farm1::S3_LOCKOUT) fdir_flags_ |= FDIR_FARM_LOCKOUT;
  else fdir_flags_ &= (uint16_t)~FDIR_FARM_LOCKOUT;
  if (loop_overruns_) fdir_flags_ |= FDIR_LOOP_OVERRUN;
}

void Flight::bus_recover(uint32_t now, const char* why) {
  recovered_once_ = true;
  last_recover_ms_ = now;
  LOGF("WARN", "I2C bus recovery (%s)", why);
  if (!bus_.recover())
    evr(3, 0x060A, "I2C bus clear: SDA or SCL still low after %u clocks", (unsigned)kI2cClearMaxPulses);
}

// =============================================================================
// Spectrometer (PB-8.6 item 3 "spectrometer"; contract 13, 26, 28)
// =============================================================================
void Flight::service_spec(uint32_t now) {
  const bool pa_keyed = tx_state_ != TX_IDLE;
  spec_.set_poll_budget_us(pa_keyed ? kPaKeyedSpecBudgetUs : kSpecPollBudgetUs);
  // No new lamp exposure while an RM3100 sample or self-test waits (lamps never lit
  // during a magnetometer sample); no new exposure at all while the PA is keyed (§13.2
  // PA-off windows). A BURST, once started, runs through transmissions (C-26).
  spec_.set_lamp_gate(!mag_sample_pending_ && bist_pending_ == 0);
  spec_.set_exposure_gate(!pa_keyed);
  (void)spec_.poll(now);
  drain_burst();
  if (spec_.result_ready() && (spec_.result().mode != SPEC_BURST || spec_.burst_available() == 0))
    handle_spec_result(now);
  // SPECDIAG: one line per pass while VC0 has room (PB-2.6); the driver keeps the next one.
  if (spec_.diag_pending() && dl_.backlog(VC_RT_ENG) + kDiagEvrOctets <= kDiagBacklogMax) {
    char line[kEvrTextMax + 1];
    if (spec_.pop_diag_line(line, sizeof line)) evr(1, 0x0703, "%s", line);
  }
  spec_health(now);
  if (!(sensor_enable_ & SNS_AS7265X)) spec_start_req_ = false;
  if (spec_start_req_ && spec_.state() == As7265x::ST_IDLE && !spec_.result_ready() &&
      spec_.burst_available() == 0 && spec_.start_cycle(spec_cfg_, now)) {
    spec_start_req_ = false;
    if (spec_cfg_.mode == SPEC_BURST) {
      burst_tx_frames_ = 0;
      evr(1, 0x0704, "BURST START n=%u s cycles=%u", (unsigned)spec_cfg_.n, (unsigned)spec_cfg_.burst_cycles);
    }
  }
}

void Flight::drain_burst() {
  for (uint8_t k = 0; k < kBurstPacketsPerPass; ++k) {
    const uint8_t avail = spec_.burst_available();
    // Three samples per packet, or the rest once the burst has ended.
    if (!(avail >= kSpecBurstPerPacket || (avail > 0 && !spec_.burst_active()))) return;
    SpecBurstSample s[kSpecBurstPerPacket];
    const uint8_t n = spec_.burst_pop(s, kSpecBurstPerPacket);
    if (n == 0) return;
    const SpecExposure& ex = spec_.burst_exposure();
    uint8_t b[kMaxPayload];
    uint8_t rice_status = RICE_OK;
    const size_t len = pack_specburst(spec_.burst_t0_ms(), spec_.burst_rate_dhz(), ex.gain_code,
                                      ex.int_cycles, s, n, b, sizeof b, rice_status);
    if (rice_status != RICE_OK && rice_status != RICE_ERR_OVERFLOW)
      evr(2, 0x0704, "BURST rice status %u", (unsigned)rice_status);
    // Recorded in the SSR; the real-time push fails when VC1 is full (overflows(1)).
    if (len) (void)emit(APID_SPECBURST, b, len, VC_RT_SCI);
  }
}

void Flight::handle_spec_result(uint32_t now) {
  (void)now;
  const SpecResult& r = spec_.result();
  SpecAttitude att;
  (void)spec_attitude(att);
  SpecV31 v;
  const SpecEvents e = spec_proc_.process(r, att, sclk_.seconds(), v);
  uint8_t b[kMaxPayload];
  const size_t n = pack_spec_v31(v, b, sizeof b);
  if (n) (void)emit(APID_SPEC, b, n, VC_RT_SCI);
  // F-04: LOCKIN / FLUOR whose lamps all sit on absent slaves -> invalid packet (sent
  // above) and one EVR per configuration.
  if ((r.mode == SPEC_LOCKIN || r.mode == SPEC_FLUOR) && !(r.flags & SPEC_F_VALID) &&
      spec_.last_error() == As7265x::ERR_NO_LAMP && !no_lamp_reported_) {
    no_lamp_reported_ = true;
    evr(2, 0x0707, "AS7265X %s", "no lamp on a present device: LOCKIN/FLUOR invalid");
  }
  if (r.mode == SPEC_BURST) {
    // F-06 / C-26: longest sample read and the frames transmitted while the burst ran.
    evr(1, 0x0704, "BURST END samples=%u rate=%u.%u Hz dropped=%u readmax=%u ms tx=%u",
        (unsigned)r.burst_samples, (unsigned)(r.burst_rate_dhz / 10u), (unsigned)(r.burst_rate_dhz % 10u),
        (unsigned)r.burst_dropped, (unsigned)r.burst_read_max_ms, (unsigned)burst_tx_frames_);
  }
  if (e.spectral_event) {
    const unsigned th = spec_proc_.event_threshold_cdeg();
    evr(1, 0x0701, "spectral event: angle %u.%02u deg (threshold %u.%02u)", (unsigned)(e.angle_cdeg / 100u),
        (unsigned)(e.angle_cdeg % 100u), th / 100u, th % 100u);
  }
  if (e.class_changed)
    evr(1, 0x0702, "light source %s -> %s (%u %%)", spec_class_name(e.old_class),
        spec_class_name(e.new_class), (unsigned)e.conf);
  spec_.consume_result();
}

void Flight::spec_health(uint32_t now) {
  const As7265x::State st = spec_.state();
  // F-07 (AS-PROT-7): the health bit follows the driver at run time.
  if (spec_.ok()) sensor_health_ |= SNS_AS7265X;
  else sensor_health_ &= (uint16_t)~SNS_AS7265X;
  // EVR 0x0707 on the stable states only (INIT / RESET are transitional).
  SpecReport cur = spec_reported_;
  if (spec_.ok()) cur = SPEC_REP_OK;
  else if (st == As7265x::ST_ABSENT) cur = SPEC_REP_ABSENT;
  else if (st == As7265x::ST_FAULT) cur = SPEC_REP_FAULT;
  const bool became_ok = cur == SPEC_REP_OK && spec_reported_ != SPEC_REP_OK;
  const bool entered_fault = cur == SPEC_REP_FAULT && spec_reported_ != SPEC_REP_FAULT;
  if (cur != spec_reported_) {
    spec_reported_ = cur;
    if (cur == SPEC_REP_OK) evr(2, 0x0707, "AS7265X %s", "available again");
    else evr(2, 0x0707, "AS7265X %s", cur == SPEC_REP_ABSENT ? "ABSENT" : "FAULT");
  }
  // LAMP STATE UNKNOWN once per episode: the driver's retries pass through INIT / RESET
  // (lamp_state_unknown() false meanwhile), but the episode ends only when a read-back
  // shows every lamp dark (lamps_lit() false) or the instrument works again.
  if (spec_.lamp_state_unknown() && !spec_unknown_reported_) {
    spec_unknown_reported_ = true;
    evr(2, 0x0707, "AS7265X %s", "LAMP STATE UNKNOWN");
  } else if (spec_unknown_reported_ && (!spec_.lamps_lit() || spec_.ok())) {
    spec_unknown_reported_ = false;
  }
  const bool recovered = spec_.take_recovered();
  if (recovered) evr(2, 0x0705, "AS7265X recovered by soft reset");
  if (recovered || became_ok) report_spec_identity();
  // PB-8.6 item 9 (AS-T6): a hung AS72651 may hold SDA; the FAULT path escalates to the
  // bus clear when the bus itself is failing (rate-limited with the FDIR response).
  if (entered_fault && bus_.consecutive_errors() >= kSpecFaultBusErrors &&
      (!recovered_once_ || now - last_recover_ms_ >= kBusRecoverMinMs))
    bus_recover(now, "AS7265X FAULT");
}

// Attitude for the SPEC boresight: the Nicla fusion quaternion (device -> ENU world),
// else the TRIAD solution (NED -> body, conjugated to body -> NED).
bool Flight::spec_attitude(SpecAttitude& att) {
  att = SpecAttitude();
  att.bore_body = Vec3{kSpecBoresightBody[0], kSpecBoresightBody[1], kSpecBoresightBody[2]};
  if (aru_valid_ && (aru_last_.motion_flags & 1u)) {
    att.valid = true;
    att.q_body_to_world = Quat{aru_last_.qw, aru_last_.qx, aru_last_.qy, aru_last_.qz};
    att.world = SPEC_WORLD_ENU;
    return true;
  }
  Quat q{1.0f, 0.0f, 0.0f, 0.0f};
  bool from_rm = false;
  if (!triad(q, from_rm)) return false;
  att.valid = true;
  att.q_body_to_world = spec_conj(q);
  att.world = SPEC_WORLD_NED;
  return true;
}

// =============================================================================
// Magnetometers and the ARU (PB-8.6 item 3 "MAG/ARU sampling"; F-04, F-60)
// =============================================================================
void Flight::service_mag(uint32_t now) {
  if (mag_phase_ == MAG_IDLE) {
    if (!sample_due_) return;
    sample_due_ = false;
    mag_phase_ = MAG_WAIT;
    mag_wait_t0_ = now;
    mag_sample_pending_ = true;                     // closes the lamp gate (service_spec)
  }
  if (mag_phase_ == MAG_WAIT) {
    if (tx_state_ != TX_IDLE) return;               // PA-off windows only
    // Lamps lit or in an unknown state: wait up to kSpecLampDeferMaxMs for them to go
    // dark, then sample anyway and flag it (MAG b4).
    const bool lamp = spec_.lamps_lit() || spec_.lamp_state_unknown();
    if (lamp && now - mag_wait_t0_ < kSpecLampDeferMaxMs) return;
    if (lamp) mag_lamp_ = true;
    start_mag_sample();
    mag_phase_ = MAG_COLLECT;
    mag_collect_t0_ = millis();
    if (mag_pending_[0] || mag_pending_[1]) return;  // conversion ~6.8 ms: collect next passes
  }
  // MAG_COLLECT: one STATUS read per pending unit per pass, bounded by kMagCollectTimeoutMs.
  if (tx_state_ != TX_IDLE) mag_tx_keyed_ = true;
  if (spec_.lamps_lit()) mag_lamp_ = true;
  const bool timeout = now - mag_collect_t0_ >= kMagCollectTimeoutMs;
  for (uint8_t u = 0; u < kMagUnits; ++u) {
    if (!mag_pending_[u]) continue;
    Rm3100& m = u ? mag_ib_ : mag_ob_;
    const int8_t ready = m.poll_drdy();
    if (ready == 0 && !timeout) continue;
    finish_mag_unit(u, m);                          // collect, or end the measurement on error / timeout
  }
  if (!mag_pending_[0] && !mag_pending_[1]) {
    mag_phase_ = MAG_IDLE;
    mag_sample_pending_ = false;
  }
}

// Starts both RM3100 conversions, then reads the two Nicla Sense ME pages while they
// convert (~2 x 3 ms of I2C at 100 kHz), so the ~6.8 ms conversion is hidden.
void Flight::start_mag_sample() {
  const uint16_t en = sensor_enable_;
  const bool ob = (en & SNS_RM3100_OB) && mag_ob_.ok();
  const bool ib = (en & SNS_RM3100_IB) && mag_ib_.ok();
  mag_pending_[0] = ob && mag_ob_.start();
  mag_pending_[1] = ib && mag_ib_.start();
  if (!mag_pending_[0]) rm_fresh_[0] = false;       // disabled, absent or POLL failed
  if (!mag_pending_[1]) rm_fresh_[1] = false;
  if ((en & SNS_NICLA_ME) && aru_.ok()) {
    AruReading r = aru_last_;
    if (aru_.read_motion(r)) {
      aru_valid_ = true;
      aru_fail_count_ = 0;
      if (r.motion_flags & 8u) {                    // BMM150 through the BHI260
        for (uint8_t k = 0; k < 3; ++k) last_mag_ut_[k] = (float)r.mag_raw[k] * kAruMagUtPerLsb;
        mstat_body_.add(last_mag_ut_[0], last_mag_ut_[1], last_mag_ut_[2]);
      }
      aru_env_valid_ = aru_.read_env(r);
      if (aru_env_valid_ && (r.env_flags & 4u)) bus_temp_c_ = r.t_c;
      aru_last_ = r;
      sensor_health_ = (uint16_t)((sensor_health_ & ~kMeBits) | SNS_NICLA_ME |
                                  me_bits(r.motion_flags, aru_env_valid_ ? r.env_flags : 0u));
    } else {
      aru_valid_ = aru_env_valid_ = false;
      if (aru_fail_count_ < 255u) ++aru_fail_count_;
    }
  } else {
    aru_valid_ = aru_env_valid_ = false;            // disabled: no stale attitude or environment
  }
}

void Flight::finish_mag_unit(uint8_t unit, Rm3100& m) {
  float x = 0.0f, y = 0.0f, z = 0.0f;
  const bool ok = m.collect(x, y, z, 0);            // one STATUS read, never a wait
  mag_pending_[unit] = false;
  rm_fresh_[unit] = ok;
  if (!ok) return;
  rm_ut_[unit][0] = x;
  rm_ut_[unit][1] = y;
  rm_ut_[unit][2] = z;
  if (unit) mstat_ib_.add(x, y, z);
  else mstat_ob_.add(x, y, z);
}

// MAGBIST / deferred boot self-test: one unit per pass, PA off, no magnetometer sample in
// progress, every lamp dark. A lamp whose state stays UNKNOWN (driver FAULT) is waited for
// at most kSpecLampDeferMaxMs, as for a sample.
void Flight::service_bist(uint32_t now) {
  if (!bist_pending_ || tx_state_ != TX_IDLE || mag_phase_ != MAG_IDLE) return;
  if (spec_.lamps_lit() && !(spec_.lamp_state_unknown() && now - bist_wait_t0_ >= kSpecLampDeferMaxMs))
    return;
  const uint8_t unit = (bist_pending_ & 1u) ? 0u : 1u;
  bist_pending_ = (uint8_t)(bist_pending_ & ~(1u << unit));
  run_bist_unit(unit);
}

// =============================================================================
// CFDP (PB-2.5)
// =============================================================================
void Flight::service_cfdp(uint32_t now) {
  // SSR export: at most one PDU per pass, and only while VC3 has room for the largest
  // possible next packet (VC3 never holds more than two packets).
  if (cfdp_tx_.active() &&
      dl_.backlog(VC_FILE) + kSpPriHdrLen + kSpSecHdrLen + kCfdpMaxPduLen <= kCfdpVc3BacklogMax) {
    uint8_t pdu[kCfdpMaxPduLen];
    const size_t n = cfdp_tx_.next_pdu(pdu, sizeof pdu);
    if (n) (void)emit(APID_CFDP, pdu, n, VC_FILE, false);   // a copy of a file: not recorded
  }
  if (cfdp_ssr_active_ && !cfdp_tx_.active()) {
    cfdp_ssr_active_ = false;
    ssr_.end_export();                              // recording resumes
    cfdp_last_seq_ = cfdp_tx_.seq();
    cfdp_last_pm_ = cfdp_tx_.progress_permille();
    evr(1, 0x0A01, "CFDP EOF cond %u: %lu/%lu B, %lu not recorded", (unsigned)cfdp_tx_.last_condition(),
        (unsigned long)cfdp_tx_.sent(), (unsigned long)cfdp_tx_.file_size(),
        (unsigned long)(ssr_.paused_drops() - cfdp_paused_base_));
  }
  // Relay supervision: start, silence and cancel timeouts.
  const RelayGate::Event ev = relay_gate_.poll(now, kRelayStartTimeoutMs);
  if (ev == RelayGate::EV_START_TIMEOUT) {
    evr(2, 0x0A04, "CFDP relay seq %lu: %s", (unsigned long)relay_gate_.seq(), "EGSE did not start within 30 s");
  } else if (ev == RelayGate::EV_CANCEL_TIMEOUT) {
    evr(2, 0x0A04, "CFDP relay seq %lu: %s", (unsigned long)relay_gate_.seq(), "cancelled, no EOF within 30 s");
  }
  if (relay_gate_.state() == RelayGate::ACTIVE && relay_.expired(now)) {
    cfdp_last_seq_ = relay_gate_.seq();
    cfdp_last_pm_ = relay_.progress_permille();
    relay_.reset();
    relay_gate_.reset();
    evr(2, 0x0A04, "CFDP relay seq %lu: %s", (unsigned long)cfdp_last_seq_, "silent, expired");
  }
}

// =============================================================================
// EGSE services (PB-4.1)
// =============================================================================
bool Flight::egse_set_partition(int p) {
  if (p < 1 || p > 65534) {
    evr(2, 0x0122, "SDLS TM epoch %ld refused (current %u)", (long)p, (unsigned)sdls_tm_.epoch());
    return false;
  }
  const uint16_t e = (uint16_t)p;
  const uint16_t before = sdls_tm_.epoch();
  // Nonce safety: an epoch is never lowered (a lower one = a regressed EGSE counter).
  if (!sdls_tm_.set_epoch(e)) {
    evr(2, 0x0122, "SDLS TM epoch %ld refused (current %u)", (long)p, (unsigned)before);
    return false;
  }
  sclk_.partition = e;
  if (e != before && sdls_tm_.service() == SDLS_SVC_AE)
    evr(1, 0x0120, "SDLS TM epoch %u: downlink protected", (unsigned)e);
  return true;
}

bool Flight::egse_set_sdls_sn(int sn) {
  sdls_tc_.set_last_sn((uint32_t)sn);               // modulo 2^32: the EGSE's int32 of the u32 SN
  return true;
}

bool Flight::egse_hardline_cltu(const String& hex) {
  uint8_t b[110];                                   // hl_cltu: <= 220 hex characters
  const size_t n = hex_decode(hex, b, sizeof b, 2, 220);
  if (n == 0) return false;
  LOGF("INFO", "hardline (umbilical) CLTU, %u octets", (unsigned)n);
  process_tc(b, n, true, true);
  return true;
}

int Flight::egse_cfdp_pdu(const String& hex) {
  uint8_t pdu[kCfdpRelayMaxPduLen];
  const size_t n = hex_decode(hex, pdu, sizeof pdu, 2 * kCfdpHdrLen, 2 * kCfdpRelayMaxPduLen);
  if (n == 0) return -1;                            // bad hex or length
  // Busy (retry): VC3 lacks room for this packet, or SDLS TM waits for its epoch.
  if (!sdls_tm_.ready() || dl_.backlog(VC_FILE) + kSpPriHdrLen + kSpSecHdrLen + n > kCfdpVc3BacklogMax) return 0;
  const uint32_t now = millis();
  if (relay_gate_.admit(pdu, n, now) != 1) return -1;   // not the authorised transfer (counted)
  if (!emit(APID_CFDP, pdu, n, VC_FILE, false)) return 0;
  relay_.observe(pdu, n, now);
  if (relay_gate_.state() == RelayGate::NONE) {     // the admitted PDU was the EOF
    cfdp_last_seq_ = relay_gate_.seq();
    cfdp_last_pm_ = relay_.progress_permille();
    evr(1, 0x0A05, "CFDP relay seq %lu EOF cond %u", (unsigned long)relay_gate_.seq(),
        (unsigned)relay_.last_condition());
  }
  return 1;
}

// =============================================================================
// EGSE notifications (PB-0.4): never wait for the router UART
// =============================================================================
bool Flight::notify_room(size_t payload_octets) const {
  const int room = VGQ_ROUTER_SERIAL.availableForWrite();
  return room > 0 && (size_t)room >= payload_octets + kNotifyMargin;
}

bool Flight::send_cadu(const uint8_t* cadu) {
  if (large_sent_ || !notify_room(kCaduHexLen)) return false;
  Bridge.notify("tm_cadu", to_hex(cadu, kCaduLen));
  large_sent_ = true;
  return true;
}

// One pending copy: the older one leaves first; a third while one waits is dropped.
void Flight::queue_cadu_copy(const uint8_t* cadu) {
  if (cadu_copy_valid_) {
    if (send_cadu(cadu_copy_)) {
      memcpy(cadu_copy_, cadu, kCaduLen);
    } else {
      ++cadu_nd_;
    }
    return;
  }
  if (!send_cadu(cadu)) {
    memcpy(cadu_copy_, cadu, kCaduLen);
    cadu_copy_valid_ = true;
  }
}

void Flight::flush_notifications(uint32_t now) {
  (void)now;
  // Small notifications first (a few dozen octets each, not "large").
  if (boot_note_pending_ && notify_room(8)) {
    Bridge.notify("sc_boot", (int)reset_cause_);
    boot_note_pending_ = false;
  }
  if (sdls_sn_pending_ && notify_room(16)) {
    Bridge.notify("sdls_sn", (int)as_i32(sdls_tc_.last_sn()));   // the latest value is enough
    sdls_sn_pending_ = false;
  }
  if (cfdp_req_pending_) {
    const size_t n = strlen(cfdp_req_text_);
    if (notify_room(n)) {
      Bridge.notify("cfdp_req", text_string(cfdp_req_text_, n));
      cfdp_req_pending_ = false;
    }
  }
  if (cfdp_cancel_pending_) {
    char t[12];
    const int n = snprintf(t, sizeof t, "%lu", (unsigned long)cfdp_cancel_seq_);
    if (n > 0 && (size_t)n < sizeof t && notify_room((size_t)n)) {
      Bridge.notify("cfdp_cancel", text_string(t, (size_t)n));
      cfdp_cancel_pending_ = false;
    }
  }
  // Large notifications: at most one per pass.
  if (cadu_copy_valid_ && send_cadu(cadu_copy_)) cadu_copy_valid_ = false;
  if ((status_due_ || status_x_due_) && !large_sent_) {
    EgseStatus s;
    fill_status(s);
    char j[kEgseStatusCap];
    if (status_due_) {
      const size_t n = format_sc_status(s, j, sizeof j);
      if (n == 0) {
        status_due_ = false;                        // cannot be formatted: nothing to send
      } else if (notify_room(n)) {
        Bridge.notify("sc_status", text_string(j, n));
        large_sent_ = true;
        status_due_ = false;
      }
    }
    if (status_x_due_ && !large_sent_) {
      const size_t n = format_sc_status_x(s, j, sizeof j);
      if (n == 0) {
        status_x_due_ = false;
      } else if (notify_room(n)) {
        Bridge.notify("sc_status_x", text_string(j, n));
        large_sent_ = true;
        status_x_due_ = false;
      }
    }
  }
}

void Flight::fill_status(EgseStatus& s) {
  s = EgseStatus();
  uint32_t busy = 0;
  for (uint8_t i = 0; i < 60; ++i) busy += busy_ms_bucket_[i];
  s.mode = mode_;
  s.sclk = sclk_.seconds();
  s.part = sclk_.partition;
  s.epoch = sdls_tm_.epoch();
  s.tm_state = sdls_tm_.state();
  s.tm_sn = sdls_tm_.last_sn();
  s.frames = frames_sent_;
  s.oid = oid_sent_;
  s.mcfc = dl_.mcfc();
  s.period_ms = hibernating_ ? (uint32_t)beacon_s_ * 1000u : period_now_ms();
  s.busy_ms = last_airtime_ms_;
  s.duty_pct = (float)busy / 600.0f;               // ms in 60 s -> %
  s.model = radio_.model();
  s.fr = dl_.framing() == FRAMING_USLP ? 1u : 0u;
  s.ch = rcfg_.channel;
  s.code = rcfg_.rate_code;
  s.pwr = rcfg_.power_code;
  s.lbt = rcfg_.lbt;
  s.tx = tx_state_ != TX_IDLE;
  s.inhibit = tx_inhibit_;
  s.hib = hibernating_;
  s.beacon = beacon_.level();
  s.ul_rssi = uplink_rssi_;
  s.ul_snr_cdb = uplink_snr_cdb_;
  s.noise = noise_dbm_;
  s.farm = farm_.state();
  s.vr = farm_.vr();
  s.acc = cmd_acc_;
  s.rej = cmd_rej_;
  s.fdir = fdir_flags_;
  s.sns = sensor_health_;
  for (uint8_t v = 0; v < 4; ++v) s.vc[v] = sat16((uint32_t)dl_.backlog(v));
  s.ssr_pm = ssr_.fill_permille();
  s.bus_c = bus_temp_c_;
  s.rf_fault = radio_fault_code_;
  s.tc_svc = sdls_tc_.service();
  s.tm_svc = sdls_tm_.service();
  cfdp_hk(s.cfdp, s.cfdp_seq, s.cfdp_pm);
  s.seq = seq_.state();
  s.tc_rescued = tc_rescued_;
  s.evr_nd = evr_nd_;
  s.cadu_nd = cadu_nd_;
  s.emit_ref = emit_refused_;
  s.relay_ref = relay_gate_.refused();
  s.stretch = load_.stretch_x100;
}

// =============================================================================
// Status display (4 Hz)
// =============================================================================
void Flight::update_display(uint32_t now) {
  ScDisplayData d{};
  d.mode = mode_;
  d.tx_on = tx_state_ != TX_IDLE;
  d.rx_flash = now - last_rx_flash_ms_ < kRxFlashMs;
  d.farm_lockout = farm_.state() == Farm1::S3_LOCKOUT;
  d.fdir_active = (fdir_flags_ & (uint16_t)~(FDIR_TX_INHIBIT | FDIR_HIBERNATE)) != 0;
  d.vc0_pm = permille_of_vc(dl_.backlog(VC_RT_ENG));
  d.vc1_pm = permille_of_vc(dl_.backlog(VC_RT_SCI));
  d.ssr_pm = ssr_.fill_permille();
  d.sensor_health = sensor_health_;
  d.beacon = beacon_.level();
  display_.update(d);
}

