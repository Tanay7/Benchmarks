#!/usr/bin/env python3
"""Generates docs/05_Telemetry_and_Command_Dictionary.md from the code itself.

Sources (the single sources of truth):
  ground/dssq/dictionary.py                       packets, commands, directives, bit maps
  spacecraft/vgq1_flight/sketch/src/fsw/flight.cpp event reports (EVR ids / severity / text)
  spacecraft/vgq1_flight/sketch/src/fsw/flight.cpp mode cadence table

The flight half of every packet is checked against the same dictionary by
ground/tests/test_cross_check.py, so this document cannot drift from the code.

Usage:  python3 tools/gen_dictionary_doc.py      (re-run after changing the dictionary)
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "ground"))
from dssq.dictionary import (COMMANDS, DIRECTIVES, FDIR_BITS, GROUND_DIRECTIVES,  # noqa: E402
                             PACKETS, RADIO_FAULTS, SENSOR_BITS)

FLIGHT = (ROOT / "spacecraft/vgq1_flight/sketch/src/fsw/flight.cpp").read_text()
OUT = ROOT / "docs" / "05_Telemetry_and_Command_Dictionary.md"
CODE = {"B": "u8", "b": "i8", "H": "u16", "h": "i16", "I": "u32", "i": "i32", "f": "f32"}
SEV = ["DIAG", "INFO", "WARN", "ERROR", "FATAL"]


def _c(text) -> str:
    """Escapes "|" so free text cannot split a Markdown table cell."""
    return str(text).replace("|", "\\|")


def packets() -> list[str]:
    out = []
    for apid, spec in PACKETS.items():
        size = struct.calcsize(">" + "".join(f[1] for f in spec["fields"]))
        out += [f"### APID 0x{apid:03X} - {spec['name']}: {spec['desc']} ({size} octets of user data)", "",
                "| # | Offset | Field | Type | Scale | Unit | Limits (red low / yellow low / yellow high / red high) | Description |",
                "|---|---|---|---|---|---|---|---|"]
        off = 0
        for i, (name, code, scale, unit, desc, lim) in enumerate(spec["fields"]):
            lim_s = " / ".join("-" if x is None else f"{x:g}" for x in lim) if lim else ""
            sc = "raw" if scale is None else f"{scale:g}"
            out.append(f"| {i} | {off} | `{name}` | {CODE[code]} | {sc} | {_c(unit)} | {lim_s} | {_c(desc)} |")
            off += struct.calcsize(">" + code)
        out.append("")
    return out


def commands() -> list[str]:
    out = ["| Mnemonic | Opcode | Arguments (name: type, range) | Hazardous | Description |",
           "|---|---|---|---|---|"]
    for c in sorted(COMMANDS.values(), key=lambda c: c.opcode):
        args = ", ".join(f"{n}: {CODE[t]} {lo}..{hi}" + (f" ({', '.join(f'{k}={v}' for k, v in e.items())})" if e else "")
                         for n, t, lo, hi, e in c.args) or "-"
        out.append(f"| `{c.mnemonic}` | 0x{c.opcode:02X} | {args} | {'YES' if c.hazardous else ''} | {_c(c.desc)} |")
    return out


def evrs() -> list[str]:
    rows = {}
    for m in re.finditer(r'evr\((\d),\s*(0x[0-9A-Fa-f]+)(\s*\+\s*[a-z_]+)?\s*,\s*"([^"]*)"', FLIGHT):
        sev, eid, plus, text = int(m.group(1)), int(m.group(2), 16), m.group(3), m.group(4)
        key = f"0x{eid:04X}" + ("+n" if plus else "")
        rows.setdefault(key, (SEV[sev], text))
    out = ["| Event id | Severity | Text (printf format) |", "|---|---|---|"]
    for k in sorted(rows):
        sev, text = rows[k]
        out.append(f"| {k} | {sev} | `{_c(text)}` |")
    return out


def cadence() -> list[str]:
    block = FLIGHT[FLIGHT.index("static const uint16_t kCadence"):]
    block = block[:block.index("};")]
    out = ["| Mode | HK | RF | TIMECORR | MAG | ATT | SPEC | ENV |", "|---|---|---|---|---|---|---|---|"]
    for m in re.finditer(r"/\*\s*(\w+)\s*\*/\s*\{([^}]*)\}", block):
        vals = [v.strip() for v in m.group(2).split(",")]
        out.append(f"| {m.group(1)} | " + " | ".join("off" if v == "0" else f"{v} s" for v in vals) + " |")
    return out


def main():
    lines = [
        "# 05 - Telemetry & Command Dictionary",
        "",
        "> GENERATED by `tools/gen_dictionary_doc.py` from `ground/dssq/dictionary.py` and the flight "
        "source. Do not edit by hand; re-run the script. The flight packers are verified against the same "
        "dictionary by `ground/tests/test_cross_check.py` (bit-exact).",
        "",
        "Conventions: all fields big-endian (CCSDS network order). Engineering value = raw x scale. "
        "Sentinels mean *not available* and are shown as `None`/`-`: i16 0x7FFF, u16 0xFFFF, "
        "i32 0x7FFFFFFF, u32 0xFFFFFFFF, i8 -128; f32 NaN. Every TM packet carries a 6-octet CUC "
        "secondary header (SCLK, CCSDS 301.0-B-4, 4+2 octets) before the user data listed here.",
        "",
        "## 1 Telemetry packets", "",
        "APID 0x012 (EVR) and 0x015 (RFSCAN) are variable length:",
        "",
        "* **EVR**: `severity u8 | event_id u16 | ASCII text (<= 80 chars)`",
        "* **RFSCAN**: `first_ch u8 | count u8 | duration_ms u16 | noise_dbm i8 x count` (-128 = no reading)",
        "",
        *packets(),
        "## 2 Packet generation cadence per flight-software mode", "",
        "Seconds between packets (overridable per packet with `PKTRATE`). EVR, CMDVER and RFSCAN are "
        "event driven.", "",
        *cadence(), "",
        "## 3 Bit maps", "",
        "### HK.fdir_flags", "", "| Bit | Name |", "|---|---|",
        *[f"| {i} | {n} |" for i, n in enumerate(FDIR_BITS)], "",
        "### HK.sensor_health (and the SENSORS enable mask: bits 0, 7, 11, 12, 13)", "",
        "| Bit | Name |", "|---|---|", *[f"| {i} | {n} |" for i, n in enumerate(SENSOR_BITS)], "",
        "### HK.radio_fault (E22 abnormal-status self-report)", "",
        "| Code | Meaning |", "|---|---|", *[f"| {k} | {_c(v)} |" for k, v in RADIO_FAULTS.items()], "",
        "## 4 Telecommands (uplinked; APID 0x0C0, user data = opcode + arguments)", "",
        "Typed identically on the web console and on CardKB #1. Hazardous commands need CONFIRM (and "
        "2nd-operator AUTH when the two-person rule is enabled). Prefix any command with `BD` to send it "
        "as a COP-1 bypass (Type-BD) frame.", "",
        *commands(), "",
        "### COP-1 control directives (Type-BC frames)", "", "| Directive | Meaning |", "|---|---|",
        *[f"| `{k}` | {_c(v)} |" for k, v in DIRECTIVES.items()], "",
        "### Ground-station directives (executed by the GDS / Radio Control Unit)", "",
        "| Directive | Meaning |", "|---|---|", *[f"| `{k}` | {_c(v)} |" for k, v in GROUND_DIRECTIVES.items()], "",
        "## 5 Event reports (EVR, APID 0x012)", "",
        "Extracted from `flight.cpp`. `+n` = base id plus a code (e.g. the TC rejection reason).", "",
        *evrs(), "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
