#!/usr/bin/env python3
"""Generate the SDLS (CCSDS 355.0-B) uplink authentication key for BOTH ends.

Writes (both git-ignored — never commit keys):
  ground/config/sdls_key.hex                         used by the GDS ([sdls] key_file)
  spacecraft/vgq1_flight/sketch/src/sdls_key.h       compiled into the flight software

Then set  [sdls] enabled = true  in ground/config/station.toml and rebuild/upload
the flight sketch. Both ends must hold the same key and SPI.

Usage:  python3 tools/gen_sdls_key.py [--spi 1] [--force]
"""
import argparse
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUND = ROOT / "ground" / "config" / "sdls_key.hex"
FLIGHT = ROOT / "spacecraft" / "vgq1_flight" / "sketch" / "src" / "sdls_key.h"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spi", type=int, default=1, help="Security Parameter Index (1..65535)")
    ap.add_argument("--force", action="store_true", help="overwrite existing keys")
    a = ap.parse_args()
    if (GROUND.exists() or FLIGHT.exists()) and not a.force:
        sys.exit("keys already exist (use --force to replace them on BOTH ends)")
    key = secrets.token_bytes(32)                     # 256-bit key from the OS CSPRNG
    GROUND.write_text(key.hex() + "\n")
    GROUND.chmod(0o600)
    body = ", ".join(f"0x{b:02X}" for b in key)
    FLIGHT.write_text(
        "// GENERATED by tools/gen_sdls_key.py - DO NOT COMMIT (listed in .gitignore)\n"
        "#pragma once\n#include <stdint.h>\n"
        f"#define VGQ_SDLS_SPI {a.spi}\n"
        f"static const uint8_t kVgqSdlsKey[32] = {{{body}}};\n")
    print(f"SDLS key written:\n  {GROUND}\n  {FLIGHT}\nSPI = {a.spi}. Now set [sdls] enabled = true "
          "and re-upload the flight sketch.")


if __name__ == "__main__":
    main()
